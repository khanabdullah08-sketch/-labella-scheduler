#!/usr/bin/env node
/**
 * Generates supabase/seed/<tenant>.sql from tenants/<tenant>/tenant.json + catalog.json,
 * so the database and the website are built from ONE source of truth.
 *
 *   node scripts/gen-seed.mjs labella
 *
 * The seed is idempotent (upserts): re-running it after editing prices/menus updates the database.
 * It never deletes; to retire a service set active = false in the database.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const q = v => "'" + String(v).replace(/'/g, "''") + "'";

export function generateSeed(tenant) {
  if (!/^[a-z0-9_-]+$/.test(tenant || '')) throw new Error('Usage: node scripts/gen-seed.mjs <tenant>');
  const dir = path.join(ROOT, 'tenants', tenant);
  const t = JSON.parse(fs.readFileSync(path.join(dir, 'tenant.json'), 'utf8'));
  const cat = JSON.parse(fs.readFileSync(path.join(dir, 'catalog.json'), 'utf8'));
  if (t.backend !== 'v2') throw new Error(`Tenant "${tenant}" uses the legacy backend; seeds are only for backend "v2".`);

  const slug = q(t.slug);
  const r = t.rules;
  const phoneRe = '^' + t.locale.phonePattern + '$';
  const out = [];
  let part = 0;
  const mark = what => `-- ===== PART ${++part}: ${what} =====`;
  out.push(`-- GENERATED by scripts/gen-seed.mjs from tenants/${tenant}/ -- do not edit by hand.`);
  out.push(`-- Safe to re-run: every statement is an upsert. If a run fails, you can select and run one PART at a time`);
  out.push(`-- (in order); each part is a complete statement on its own, so the failing part shows which line is at fault.`);
  out.push('', 'begin;', '');

  out.push(`${mark('tenant settings')}
insert into public.tenants (slug, name, ref_prefix, timezone, phone_pattern, hold_minutes, buffer_mins,
  lead_mins, slot_step, booking_window_days, therapist_daily_cap)
values (${slug}, ${q(t.brand.name)}, ${q(t.brand.refPrefix.replace(/-?$/, '-'))}, ${q(t.timezone)}, ${q(phoneRe)},
  ${r.holdMinutes}, ${r.bufferMins}, ${r.leadMins}, ${r.slotStep}, ${r.bookingDays}, ${r.therapistMax})
on conflict (slug) do update set name = excluded.name, ref_prefix = excluded.ref_prefix, timezone = excluded.timezone,
  phone_pattern = excluded.phone_pattern, hold_minutes = excluded.hold_minutes, buffer_mins = excluded.buffer_mins,
  lead_mins = excluded.lead_mins, slot_step = excluded.slot_step,
  booking_window_days = excluded.booking_window_days, therapist_daily_cap = excluded.therapist_daily_cap;`, '');

  for (const code of Object.keys(cat.menus)) {
    out.push(`${mark('menu ' + code)}
insert into public.menus (tenant_id, code, name)
select t.id, ${q(code)}, ${q((cat.menuNames && cat.menuNames[code]) || code)} from public.tenants t where t.slug = ${slug}
on conflict (tenant_id, code) do update set name = excluded.name;`, '');
  }

  cat.branches.forEach((b, i) => {
    out.push(`${mark('branch ' + b.id)}
insert into public.branches (tenant_id, code, name, short_name, city, address, phone, rooms, open_min, close_min, menu_id, sort)
select t.id, ${q(b.id)}, ${q(b.name)}, ${q(b.shortName)}, ${q(b.city)}, ${q(b.address)}, ${q(b.phone)}, ${b.rooms},
  ${b.openMin ?? r.openMin}, ${b.closeMin ?? r.closeMin}, m.id, ${i}
from public.tenants t join public.menus m on m.tenant_id = t.id and m.code = ${q(b.menu)}
where t.slug = ${slug}
on conflict (tenant_id, code) do update set name = excluded.name, short_name = excluded.short_name, city = excluded.city,
  address = excluded.address, phone = excluded.phone, rooms = excluded.rooms, open_min = excluded.open_min,
  close_min = excluded.close_min, menu_id = excluded.menu_id, sort = excluded.sort;`, '');
  });

  for (const [code, list] of Object.entries(cat.menus)) {
    const svcRows = list.map((s, i) => `  (${q(s.id)}, ${q(s.cat)}, ${q(s.name)}, ${q(s.desc)}, ${i})`).join(',\n');
    out.push(`${mark('services of menu ' + code)}
insert into public.services (tenant_id, menu_id, code, category, name, description, sort)
select m.tenant_id, m.id, v.code, v.category, v.name, v.description, v.sort
from public.menus m join public.tenants t on t.id = m.tenant_id
cross join (values
${svcRows}
) as v(code, category, name, description, sort)
where t.slug = ${slug} and m.code = ${q(code)}
on conflict (menu_id, code) do update set category = excluded.category, name = excluded.name,
  description = excluded.description, sort = excluded.sort;`, '');

    const optRows = list.flatMap(s => s.options.map((o, i) => `  (${q(s.id)}, ${o.duration}, ${o.price}, ${i})`)).join(',\n');
    out.push(`${mark('durations and prices of menu ' + code)}
insert into public.service_options (tenant_id, service_id, duration_min, price, sort)
select s.tenant_id, s.id, v.duration_min, v.price, v.sort
from public.services s
join public.menus m on m.id = s.menu_id
join public.tenants t on t.id = m.tenant_id
join (values
${optRows}
) as v(code, duration_min, price, sort) on v.code = s.code
where t.slug = ${slug} and m.code = ${q(code)}
on conflict (service_id, duration_min) do update set sort = excluded.sort;   -- prices and on/off are owned by the Menu & Prices tab: re-running this file never resets them`, '');
  }

  out.push('commit;', '');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const tenant = process.argv[2];
    const sql = generateSeed(tenant);
    const file = path.join(ROOT, 'supabase', 'seed', tenant + '.sql');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, sql);
    console.log('Wrote ' + path.relative(ROOT, file));
  } catch (e) { console.error(e.message); process.exit(1); }
}
